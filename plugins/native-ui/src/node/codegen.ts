import {
	cssIdent,
	cssString,
	cssTokenValue,
	cssVarName,
} from "@fcalell/cli/css";
import type { ResolvedTheme } from "@fcalell/ui-core/derive";
import { modeBlocks, themeDeclarations, utilityBlocks } from "./theme.ts";

// Inputs for the `.stack/global.css` derivation. `plugin-native-ui` resolves
// the consumer's `theme` option through ui-core's `deriveTheme` and renders
// the single uniwind entry stylesheet from it.
interface CodegenGlobalCssPayload {
	resolved: ResolvedTheme;
	// `@source` roots: docs/architecture/plugins/native-ui.md, "Stylesheet".
	sources: string[];
}

// The label an escape error names: docs/architecture/codegen.md, "CSS escape boundary".
const LABEL = "plugin-native-ui";

const GENERATED_BANNER =
	"/* Generated by @fcalell/plugin-native-ui — do not edit. */\n/* Configure tokens / fonts through stack.config.ts, not this file. */";

// Renders the uniwind entry stylesheet: docs/architecture/codegen.md, "CSS escape boundary".
export function aggregateGlobalCss(payload: CodegenGlobalCssPayload): string {
	const lines: string[] = [GENERATED_BANNER, ""];

	lines.push("@import 'tailwindcss';");
	lines.push("@import 'uniwind';");
	lines.push("");

	for (const src of payload.sources) {
		lines.push(`@source ${cssString(src)};`);
	}
	if (payload.sources.length > 0) lines.push("");

	lines.push("@theme {");
	const declarations = themeDeclarations(payload.resolved);
	for (const [name, value] of Object.entries(declarations)) {
		lines.push(`\t${cssVarName(name, LABEL)}: ${cssTokenValue(value, LABEL)};`);
	}
	lines.push("}");
	lines.push("");

	for (const [name, declarations] of utilityBlocks()) {
		lines.push(`@utility ${cssIdent(name, LABEL)} {`);
		for (const [property, value] of Object.entries(declarations)) {
			lines.push(`\t${property}: ${cssTokenValue(value, LABEL)};`);
		}
		lines.push("}");
		lines.push("");
	}

	lines.push("@layer theme {");
	lines.push("\t:root {");
	for (const [mode, colors] of modeBlocks(payload.resolved)) {
		lines.push(`\t\t@variant ${cssIdent(mode, LABEL)} {`);
		for (const [name, value] of Object.entries(colors)) {
			lines.push(
				`\t\t\t${cssVarName(name, LABEL)}: ${cssTokenValue(value, LABEL)};`,
			);
		}
		lines.push("\t\t}");
	}
	lines.push("\t}");
	lines.push("}");

	return `${lines.join("\n")}\n`;
}

import { execFileSync } from "node:child_process";
import {
	existsSync,
	mkdirSync,
	readdirSync,
	readFileSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { storyNameFromExport, toId } from "storybook/internal/csf";

const dirname = path.dirname(fileURLToPath(import.meta.url));

const STORIES_DIR = path.join(dirname, "..", "stories");
const ROSTER_DIR = path.join(dirname, "..", "src", "roster");
export const CLASS_SETS_FILE = path.join(ROSTER_DIR, "class-sets.ts");
export const SCENES_DIR = path.join(ROSTER_DIR, "scenes");

interface RosterComponent {
	layer: string;
	component: string;
	stories: string[];
	lone: string[];
}

const pascal = (word: string) => `${word[0]?.toUpperCase()}${word.slice(1)}`;
const kebab = (name: string) =>
	name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

function list(): RosterComponent[] {
	const out = execFileSync(
		process.execPath,
		[path.join(dirname, "roster-list.ts")],
		{ cwd: dirname, encoding: "utf8" },
	);
	return (JSON.parse(out) as { components: RosterComponent[] }).components;
}

const titleOf = (entry: RosterComponent) => `${entry.layer}/${entry.component}`;
// A component's drawer, `draw<Name>` in `scenes/<kebab>.tsx`, or none.
function drawerOf(entry: RosterComponent) {
	const file = `${kebab(entry.component)}.tsx`;
	if (!existsSync(path.join(SCENES_DIR, file))) return undefined;
	const name = `draw${entry.component}`;
	return {
		name,
		line: `import { ${name} } from "../src/roster/scenes/${file}";`,
	};
}
// A story's export name; Storybook derives the story's id from it.
const exportOf = pascal;

function moduleFor(entry: RosterComponent): string {
	const drawer = drawerOf(entry);
	return [
		"// Generated by ../roster.ts from the showcase roster; not edited.",
		`import { stateStories } from "../.storybook/state-stories.tsx";`,
		...(drawer ? [drawer.line] : []),
		"",
		`const story = stateStories(${JSON.stringify(entry.component)}${drawer ? `, ${drawer.name}` : ""});`,
		"",
		`export default { title: ${JSON.stringify(titleOf(entry))} };`,
		"",
		...entry.stories.map(
			(story) =>
				`export const ${exportOf(story)} = story(${JSON.stringify(story)});`,
		),
		"",
	].join("\n");
}

// The Specimen draws the drawn components in roster order, then each lone story as a frame.
function specimenModule(entries: RosterComponent[]): string {
	const drawn = entries.flatMap((entry) => {
		const drawer = drawerOf(entry);
		return drawer ? [{ component: entry.component, ...drawer }] : [];
	});
	const lone = entries.flatMap((entry) =>
		entry.lone.map((story) =>
			toId(titleOf(entry), storyNameFromExport(exportOf(story))),
		),
	);
	return [
		"// Generated by ../roster.ts from the showcase roster; not edited.",
		`import { specimen } from "../.storybook/state-stories.tsx";`,
		...drawn.map((entry) => entry.line),
		"",
		`export default { title: "Specimen" };`,
		"",
		"export const Rest = specimen(",
		`\t[${drawn.map((entry) => `[${JSON.stringify(entry.component)}, ${entry.name}]`).join(", ")}],`,
		`\t${JSON.stringify(lone)},`,
		");",
		"",
	].join("\n");
}

// The story modules: docs/architecture/ui-core/showcase.md, "Story generation".
export function writeStories(): void {
	mkdirSync(STORIES_DIR, { recursive: true });
	const wanted = new Map<string, string>();
	const entries = list();
	for (const entry of entries)
		wanted.set(`${entry.component}.stories.ts`, moduleFor(entry));
	wanted.set("Specimen.stories.ts", specimenModule(entries));
	for (const file of readdirSync(STORIES_DIR))
		if (!wanted.has(file)) rmSync(path.join(STORIES_DIR, file));
	for (const [file, source] of wanted) {
		const target = path.join(STORIES_DIR, file);
		if (!existsSync(target) || readFileSync(target, "utf8") !== source)
			writeFileSync(target, source);
	}
}

// `pnpm generate` runs this file, so the check type-checks the stories the roster names now.
if (import.meta.main) writeStories();
